import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toBytes } from "viem";

const PROTOCOL_COMMIT = "18706fb455b8e6b91250deba795eb791243f6827";
const sdkRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(sdkRoot, "../..");
const defaultProtocolRoot = resolve(repositoryRoot, "../index-protocol");

const targets = [
  {
    artifact: "out/Folio.sol/Folio.json",
    output: "src/index-dtf/abis/folio-v6.generated.ts",
    exportName: "folioV6Abi",
    expectedAbiSha256: "e9311d6e5bad2dbfc5a2998fe034e7c7a1e86e744428431387b8d6d491bdc30c",
    requiredFunctions: ["openAuction", "startRebalance", "version"],
  },
  {
    artifact: "out/FolioDeployer.sol/FolioDeployer.json",
    output: "src/index-dtf/abis/folio-deployer-v6.generated.ts",
    exportName: "folioDeployerV6Abi",
    expectedAbiSha256: "1a327726b0a65ebb40b1a5a2f322b7843718019ad675c7e0b9676f94828a7610",
    requiredFunctions: ["deployFolio", "deployGovernedFolio", "versionRegistry"],
  },
  {
    artifact: "out/FolioVersionRegistry.sol/FolioVersionRegistry.json",
    output: "src/index-dtf/abis/folio-version-registry.generated.ts",
    exportName: "folioVersionRegistryAbi",
    expectedAbiSha256: "21b00604ef98ae3e804e4d0e88252d2954cd459922a96f1859d8c432592faf7d",
    requiredFunctions: ["getLatestVersion", "registerVersion", "isDeprecated"],
  },
];

const options = parseArgs(process.argv.slice(2));

if (options.checkGenerated) {
  for (const target of targets) assertCheckedInModule(target);
  process.stdout.write(`Verified checked-in Index DTF v6 ABI modules for ${PROTOCOL_COMMIT}\n`);
  process.exit(0);
}

const protocolRoot = resolve(options.protocolRoot ?? defaultProtocolRoot);
const actualCommit = execFileSync("git", ["-C", protocolRoot, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

if (actualCommit !== PROTOCOL_COMMIT) {
  fail(`Expected reserve-index-dtf commit ${PROTOCOL_COMMIT}, received ${actualCommit} at ${protocolRoot}`);
}

let stale = false;

for (const target of targets) {
  const artifactPath = resolve(protocolRoot, target.artifact);
  const outputPath = resolve(sdkRoot, target.output);
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));

  if (!Array.isArray(artifact.abi)) {
    fail(`Artifact does not contain an ABI array: ${artifactPath}`);
  }

  assertArtifactProvenance(target, artifact, artifactPath);

  const functionNames = new Set(artifact.abi.filter((entry) => entry.type === "function").map((entry) => entry.name));
  for (const functionName of target.requiredFunctions) {
    if (!functionNames.has(functionName)) {
      fail(`Artifact ${artifactPath} is missing expected function ${functionName}`);
    }
  }

  const generated = renderAbiModule(target, artifact.abi);

  if (options.check) {
    let current;
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      current = undefined;
    }

    if (current !== generated) {
      stale = true;
      process.stderr.write(`Generated ABI is stale: ${outputPath}\n`);
    }
  } else {
    writeFileSync(outputPath, generated);
    process.stdout.write(`Wrote ${outputPath}\n`);
  }
}

if (stale) {
  fail("Run `pnpm abi:index-v6:sync -- --protocol-root <path>` and review the generated ABI diff.");
}

process.stdout.write(
  `${options.check ? "Verified" : "Synchronized"} Index DTF v6 ABIs from ${PROTOCOL_COMMIT} (${protocolRoot})\n`,
);

function renderAbiModule(target, abi) {
  return [
    "// Generated by packages/sdk/scripts/sync-index-dtf-v6-abis.mjs.",
    `// Source: reserve-protocol/reserve-index-dtf@${PROTOCOL_COMMIT}`,
    `// Artifact: ${target.artifact}`,
    "// Do not edit by hand; run `pnpm abi:index-v6:sync`.",
    `export const ${target.exportName} = ${JSON.stringify(abi, null, 2)} as const;`,
    "",
  ].join("\n");
}

function assertArtifactProvenance(target, artifact, artifactPath) {
  const abiSha256 = sha256(JSON.stringify(artifact.abi));
  if (abiSha256 !== target.expectedAbiSha256) {
    fail(`Artifact ABI hash mismatch for ${artifactPath}: expected ${target.expectedAbiSha256}, received ${abiSha256}`);
  }

  let metadata;
  try {
    metadata = JSON.parse(artifact.rawMetadata);
  } catch (error) {
    fail(`Artifact rawMetadata is missing or invalid: ${artifactPath} (${String(error)})`);
  }

  if (typeof metadata.sources !== "object" || metadata.sources === null) {
    fail(`Artifact rawMetadata has no source hashes: ${artifactPath}`);
  }

  for (const [sourcePath, sourceMetadata] of Object.entries(metadata.sources)) {
    const expectedHash = sourceMetadata?.keccak256;
    if (typeof expectedHash !== "string") {
      fail(`Artifact source metadata has no hash for ${sourcePath}: ${artifactPath}`);
    }

    const sourceFile = resolve(protocolRoot, sourcePath);
    let source;
    try {
      source = readFileSync(sourceFile, "utf8");
    } catch (error) {
      fail(`Unable to verify artifact source ${sourceFile}: ${String(error)}`);
    }

    const actualHash = keccak256(toBytes(source));
    if (actualHash !== expectedHash) {
      fail(`Artifact source hash mismatch for ${sourceFile}: expected ${expectedHash}, received ${actualHash}`);
    }
  }
}

function assertCheckedInModule(target) {
  const outputPath = resolve(sdkRoot, target.output);
  let current;
  try {
    current = readFileSync(outputPath, "utf8");
  } catch (error) {
    fail(`Unable to read generated ABI module ${outputPath}: ${String(error)}`);
  }

  const prefix = [
    "// Generated by packages/sdk/scripts/sync-index-dtf-v6-abis.mjs.",
    `// Source: reserve-protocol/reserve-index-dtf@${PROTOCOL_COMMIT}`,
    `// Artifact: ${target.artifact}`,
    "// Do not edit by hand; run `pnpm abi:index-v6:sync`.",
    `export const ${target.exportName} = `,
  ].join("\n");
  const suffix = " as const;\n";

  if (!current.startsWith(prefix) || !current.endsWith(suffix)) {
    fail(`Generated ABI module header or shape is stale: ${outputPath}`);
  }

  let abi;
  try {
    abi = JSON.parse(current.slice(prefix.length, -suffix.length));
  } catch (error) {
    fail(`Generated ABI module does not contain valid JSON: ${outputPath} (${String(error)})`);
  }

  const abiSha256 = sha256(JSON.stringify(abi));
  if (abiSha256 !== target.expectedAbiSha256 || current !== renderAbiModule(target, abi)) {
    fail(`Generated ABI module hash is stale: ${outputPath}`);
  }
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function parseArgs(args) {
  let check = false;
  let checkGenerated = false;
  let protocolRoot;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--") {
      continue;
    }
    if (argument === "--check") {
      check = true;
      continue;
    }
    if (argument === "--check-generated") {
      checkGenerated = true;
      continue;
    }
    if (argument === "--protocol-root") {
      protocolRoot = args[index + 1];
      if (!protocolRoot) fail("--protocol-root requires a path");
      index += 1;
      continue;
    }
    if (argument?.startsWith("--protocol-root=")) {
      protocolRoot = argument.slice("--protocol-root=".length);
      continue;
    }
    fail(`Unknown argument: ${argument}`);
  }

  if (checkGenerated && (check || protocolRoot)) {
    fail("--check-generated cannot be combined with --check or --protocol-root");
  }

  return { check, checkGenerated, protocolRoot };
}

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
